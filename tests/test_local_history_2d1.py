import numpy as np
import pytest
from app.core.v9.decoder import LocalHistoryConfig, decode_local_history
from app.core.v9.signal_renderer import signal_state_at
from app.core.state_contract import prepare_logical_query


def generated(delta=0):
    # Independent generation truth: four 80s cycles. Cycle1 A hold is offset by
    # positive shortening of its B interval; subsequent cycles start at160/240.
    durations=[40,40,40+delta,40-delta,40,40,40,40]
    labels=np.repeat(np.tile([0,1],4),durations)
    starts=np.cumsum([0]+durations)
    truth=[[int(a),int(b),i%2] for i,(a,b) in enumerate(zip(starts,starts[1:]))]
    x=np.eye(2)[labels];templates=np.array([[.98,.02],[.02,.98]])
    return x,templates,truth


@pytest.mark.parametrize('delta',[0,10,30,-10])
def test_fixed_templates_recover_independent_duration_changes(delta):
    x,templates,truth=generated(delta)
    result=decode_local_history(x,templates,80.,[40.,40.])
    assert result['status']=='ok'
    recovered=[s[0] for s in result['segments'][1:]]
    expected=[s[0] for s in truth[1:]]
    assert len(recovered)==len(expected)
    # Prespecified boundary tolerance1s, not generated by decoding.
    assert all(abs(a-b)<=1 for a,b in zip(recovered,expected))
    assert recovered[:2]==[40.,80.] and recovered[-4:]==[160.,200.,240.,280.]
    if delta:
        assert abs(recovered[2]-120.)>=9
    assert result['cause_of_deviation']=='UNKNOWN'
    assert result['calibrated_lamp_probability'] is None


@pytest.mark.parametrize('scenario',['no_demand','blocked_green'])
def test_unidentifiable_silence_is_censored_not_red(scenario):
    x,templates,_=generated();x[90:110]=0
    history=decode_local_history(x,templates,80.,[40.,40.])
    assert history['abstention_intervals']==[[90.,110.,'NO_LOCAL_VEHICLE_EVIDENCE']]
    pred={'schedule':{'phase_names':['A','B'],'period_s':80.,'raw_hsmm_segments':[[0,320,0]],
        'stream_activity_by_phase':[{'stream':'turn','event_probability_by_phase':{'A':.98,'B':.02}}]},
        'reconstruction_history':history}
    state=signal_state_at(pred,100.)
    assert state['logical_phase']['estimated_state']=='UNKNOWN'
    assert state['logical_phase']['abstention_reason']=='NO_LOCAL_VEHICLE_EVIDENCE'
    assert state['streams'][0]['state']=='UNKNOWN'
    assert history['cause_of_deviation']=='UNKNOWN'


def test_explicit_gap_and_cropped_input_do_not_claim_camera_coverage():
    x,templates,_=generated();mask=np.ones(len(x),dtype=bool);mask[85:100]=False;mask[:5]=False;mask[-5:]=False
    history=decode_local_history(x,templates,80.,[40.,40.],coverage_mask=mask)
    pred={'schedule':{'phase_names':['A','B'],'raw_hsmm_segments':[[0,320,0]]},'reconstruction_history':history}
    query=prepare_logical_query(pred)
    for t in (0,90,319):
        assert query.at(t).abstention_reason=='EXPLICIT_INPUT_COVERAGE_GAP'
    for t in (-1,320):
        assert query.at(t).abstention_reason=='NO_TEMPORAL_COVERAGE'
    assert 'NOT_camera_coverage' in history['coverage_semantics']


def test_zero_demand_and_budget_exhaustion_have_no_fabricated_history():
    x,templates,_=generated()
    empty=decode_local_history(x*0,templates,80.,[40.,40.])
    assert empty['status']=='unavailable' and empty['segments']==[]
    budget=decode_local_history(x,templates,80.,[40.,40.],config=LocalHistoryConfig(max_bins=1))
    pred={'schedule':{'phase_names':['A','B'],'raw_hsmm_segments':[[0,320,0]]},'reconstruction_history':budget}
    assert prepare_logical_query(pred).at(30).abstention_reason=='LOCAL_DECODE_WORK_BUDGET_EXCEEDED'


def test_new_history_never_falls_back_to_raw_in_its_gaps():
    pred={'schedule':{'phase_names':['A','B'],'raw_hsmm_segments':[[0,20,0]],'baseline_segments':[[0,20,0]],'period_s':20},
          'reconstruction_history':{'source':'test','status':'ok','segments':[[0,5,0],[10,15,1]]}}
    query=prepare_logical_query(pred)
    assert query.at(7).estimated_state=='UNKNOWN'
    assert query.at(12).estimated_state=='B'
    assert query.at(15).estimated_state=='UNKNOWN'
    assert prepare_logical_query(pred,mode='configured').at(7).estimated_state=='A'


def test_existing_decoder_defaults_are_unchanged(monkeypatch):
    import app.core.v9.decoder as decoder
    x,templates,_=generated();before=templates.copy();seen=[]
    original=decoder.decode_cyclic_hsmm
    def one(*args,**kw):seen.append(kw);return original(*args,**kw)
    monkeypatch.setattr(decoder,'decode_cyclic_hsmm',one)
    decode_local_history(x,templates,80.,[40.,40.])
    assert len(seen)==1 and seen[0]['initial_phase']==0
    assert np.array_equal(before,templates)
